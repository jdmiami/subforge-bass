export const NOTE_NAMES = ['C', 'C#', 'D', 'D#', 'E', 'F', 'F#', 'G', 'G#', 'A', 'A#', 'B'];

// MPC-style layout order: bottom row 0-3 (Z X C V), mid 4-7 (A S D F), top 8-11 (Q W E R)
export const PAD_HOTKEYS = ['Z', 'X', 'C', 'V', 'A', 'S', 'D', 'F', 'Q', 'W', 'E', 'R'];

export function generate12NotePads(instrument, octaveShift = 0) {
  const octMult = Math.pow(2, octaveShift);
  const octDisplay = Math.max(0, 1 + octaveShift);
  return NOTE_NAMES.map((note, index) => {
    const freq = instrument.baseFreqHz * Math.pow(2, index / 12) * octMult;
    return {
      noteIndex: index,
      noteName: `${note}${octDisplay}`,
      semitoneOffset: index,
      frequencyHz: freq,
      harmonicBoost: 1 + instrument.drive * 0.3 * (index / 11),
      filterModMultiplier: 1 + index * 0.04,
      hotkey: PAD_HOTKEYS[index],
    };
  });
}

