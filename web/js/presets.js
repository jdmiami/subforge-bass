export function createDefaultGrooveSteps() {
  const activeIndices = {
    0: 0,
    2: 0,
    3: 3,
    6: 5,
    8: 0,
    10: 7,
    11: 10,
    14: 5,
    15: 3,
  };
  return Array.from({ length: 16 }, (_, idx) => ({
    stepIndex: idx,
    active: activeIndices[idx] !== undefined,
    noteIndex: activeIndices[idx] ?? 0,
    velocity: idx % 4 === 0 ? 0.95 : 0.82,
    gate: 0.75,
    filterMod: idx >= 10 ? 0.8 : 0.5,
  }));
}

function createAcidGrooveSteps() {
  const notes = {
    0: 0, 1: 0, 3: 3, 4: 0, 6: 7, 7: 5,
    8: 0, 10: 10, 11: 7, 12: 5, 14: 3, 15: 10,
  };
  return Array.from({ length: 16 }, (_, idx) => ({
    stepIndex: idx,
    active: notes[idx] !== undefined,
    noteIndex: notes[idx] ?? 0,
    velocity: idx % 4 === 0 ? 0.98 : 0.78,
    gate: 0.65,
    filterMod: idx % 3 === 0 ? 0.92 : 0.38,
  }));
}

function createHalfTimeReeseSteps() {
  const notes = { 0: 0, 5: 3, 8: 5, 11: 7, 14: 10 };
  return Array.from({ length: 16 }, (_, idx) => ({
    stepIndex: idx,
    active: notes[idx] !== undefined,
    noteIndex: notes[idx] ?? 0,
    velocity: idx === 0 || idx === 8 ? 0.96 : 0.84,
    gate: 0.9,
    filterMod: idx >= 8 ? 0.85 : 0.42,
  }));
}

